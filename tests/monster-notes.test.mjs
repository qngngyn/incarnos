const withStats = lines => note.replace("HP: 14", `HP: 14\n${lines}`);

test("notes without the new fields retain byte-identical document JSON", () => {
  const { monster } = parseMonsterNote(note, "Lashtail Panther");
  const json = JSON.stringify(monstersToDocuments([{ monster, type: "Animals" }]));
  // SHA-256 of the same fixture generated by the pre-change importer.
  assert.equal(createHash("sha256").update(json).digest("hex"), "f43d4309f2d948054813238429d88364207026cd759c52370a1d3f1ad96f4f43");
});

test("optional Stats fields supply IP and case-insensitive token disposition", () => {
  for (const [label, value] of [["Neutral", 0], ["FRIENDLY", 1], ["hostile", -1], ["unknown", -1], ["", -1]]) {
    const { monster } = parseMonsterNote(withStats(`IP: 34\nDisposition: ${label}`), "Caster");
    const actor = monstersToDocuments([{ monster, type: "Tournament Parties" }]).find(doc => doc.type === "npc");
    assert.deepEqual(actor.system.power, { value: 34, min: 0, max: 34, bonus: 0 });
    assert.equal(actor.prototypeToken.disposition, value);
  }
  const { monster } = parseMonsterNote(note + "\nIP: 99\nRace: Human\nDisposition: Friendly", "Ordinary");
  assert.equal(monster.ip, 0, "optional fields outside Stats are ignored");
  assert.equal(monster.race, "");
  assert.equal(monster.disposition, -1);
});

test("race, talents and spells are independent linked copies with stable embedded IDs", () => {
  const source = (name, type, id) => ({ _id: id, _key: `!items!${id}`, name, type, img: "icons/svg/aura.svg",
    system: { description: "Rules", mp: 3, effect: "Cast me", passives: { con: 2 } },
    effects: [{ _id: "effect", changes: [] }], folder: "sourceFolder", flags: { other: { value: true } } });
  const sources = { races: [source("Human", "race", "human")],
    talents: [source("Tough Skin", "feature", "tough"), source("Lord of the Elements", "feature", "lord")],
    spells: [source("Blinding Smite", "spell", "smite"), source("Prayer", "spell", "prayer"), source("Persist", "spell", "persist")] };
  const before = structuredClone(sources);
  const { monster } = parseMonsterNote(withStats("Race: [[hUmAn|Person]]\nTalents: [[Tough Skin]], [[Lord of the Elements]]\nSpells: [[Blinding Smite]], [[Prayer|Heal]], [[Persist]], [[Prayer]]"), "Caster");
  const entries = [{ monster, type: "Tournament Parties" }];
  const warnings = [];
  const docs = monstersToDocuments(entries, { sources, warnings });
  const actor = docs.find(doc => doc.type === "npc");
  const copies = docs.filter(doc => doc._stats?.compendiumSource);
  assert.equal(copies.length, 6, "repeat references are embedded only once");
  for (const [pack, originals] of Object.entries(sources)) for (const original of originals) {
    const copy = copies.find(item => item.name === original.name);
    const id = stableId(`monster:Tournament Parties/Caster:item:${original._id}`);
    const uuid = `Compendium.incarnos.${pack}.Item.${original._id}`;
    assert.equal(copy._id, id);
    assert.equal(copy._key, `!actors.items!${actor._id}.${id}`);
    assert.ok(actor.items.includes(id));
    for (const field of ["img", "name", "effects"]) assert.deepEqual(copy[field], original[field]);
    // Note stats already include race/talent bonuses, so their flat passives are switched off; spells stay as they are.
    const expected = pack === "spells" ? original.system : { ...original.system, passivesEnabled: false };
    assert.deepEqual(copy.system, expected);
    assert.equal(copy.folder, null);
    assert.equal(copy.flags.core.sourceId, uuid);
    assert.equal(itemSourceUuid(copy), uuid);
  }
  assert.deepEqual(warnings, []);
  assert.deepEqual(monstersToDocuments(entries, { sources }), docs);
  copies[0].system.description = "Edit";
  copies[0].effects[0].changes.push({ key: "test" });
  assert.deepEqual(sources, before, "copies do not mutate their compendium source");
});

test("unknown race, talent and spell names warn without stopping other imports", () => {
  const { monster } = parseMonsterNote(withStats("Race: [[Missing Race]]\nTalents: [[Missing Talent]]\nSpells: [[Missing Spell]]"), "Caster");
  const warnings = [];
  assert.ok(monstersToDocuments([{ monster, type: "Tournament Parties" }], { warnings }).some(doc => doc.type === "npc"));
  assert.equal(warnings.length, 3);
  for (const name of ["Missing Race", "Missing Talent", "Missing Spell"]) assert.ok(warnings.some(w => w.includes(name)));
});

test("an imported NPC spell checks and spends the imported Incarna pool", async t => {
  const prior = Object.fromEntries(["game", "foundry", "ui"].map(key => [key, globalThis[key]]));
  t.after(() => { for (const [key, value] of Object.entries(prior)) {
    if (value === undefined) delete globalThis[key]; else globalThis[key] = value;
  } });
  globalThis.game = { combats: [] };
  globalThis.foundry = { utils: { isEmpty: object => !Object.keys(object).length } };
  const warnings = [];
  globalThis.ui = { notifications: { warn: warning => warnings.push(warning) } };
  const { monster } = parseMonsterNote(withStats("IP: 34\nSpells: [[Prayer]]"), "Caster");
  const docs = monstersToDocuments([{ monster, type: "Tournament Parties" }], { sources: {
    spells: [{ _id: "prayer", _key: "!items!prayer", name: "Prayer", type: "spell", system: { mp: 8, actions: 2 } }]
  } });
  const actor = docs.find(doc => doc.type === "npc");
  actor.items = docs.filter(doc => doc._key.startsWith(`!actors.items!${actor._id}.`));
  actor.update = async changes => { actor.system.power.value = changes["system.power.value"]; };
  const item = actor.items.find(doc => doc.type === "spell");
  item.actor = actor;
  const cost = checkCastCost(item, { mp: item.system.mp, actions: item.system.actions });
  assert.deepEqual(await spendCastCost(actor, cost, item.name), { mp: 8, actions: 0 });
  assert.equal(actor.system.power.value, 26);
  assert.equal(actor.system.power.max, 34);
  assert.equal(checkCastCost(item, { mp: 27 }), null);
  assert.match(warnings[0], /Not enough Incarna/);
});

test("nested folders retain top-level and actor IDs and cap nesting at four folders", () => {
  const { monster } = parseMonsterNote(note, "Example");
  const paths = ["Tournament Parties/Party", "Tournament Parties/Party/Sub/Deep/Too/Deep", "Animals", ""];
  const docs = monstersToDocuments(paths.map((folderPath, i) => ({ monster: { ...monster, name: `Example ${i}` }, type: folderPath.split("/")[0], folderPath })));
  const folders = docs.filter(doc => doc.type === "Actor");
  assert.equal(folders.length, 5);
  for (const path of ["Animals", "Tournament Parties", "Tournament Parties/Party", "Tournament Parties/Party/Sub", "Tournament Parties/Party/Sub/Deep"]) {
    const folder = folders.find(doc => doc._id === stableId(`folder:monsters:${path}`));
    assert.ok(folder, path);
    assert.equal(folder.name, path.split("/").at(-1));
    assert.equal(folder.folder, path.includes("/") ? stableId(`folder:monsters:${path.slice(0, path.lastIndexOf("/"))}`) : null);
  }
  const actors = docs.filter(doc => doc.type === "npc");
  assert.equal(actors[0].folder, stableId("folder:monsters:Tournament Parties/Party"));
  assert.equal(actors[1].folder, stableId("folder:monsters:Tournament Parties/Party/Sub/Deep"));
  assert.equal(actors[3].folder, null);
  actors.forEach((actor, i) => assert.equal(actor._id, stableId(`monster:${paths[i].split("/")[0]}/Example ${i}`)));
});

