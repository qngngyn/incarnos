/**
 * Parser for the condition notes in the Obsidian vault: `System Files/Listen/Conditions/*.md`, one condition per
 * note written like a weapon trait ("Burn (dice, e.g. D4): You get that many Burn tokens. …"), optionally followed by
 * a line "Icon: icons/svg/fire.svg". The result becomes Foundry's status effect list (module/data/conditions.mjs).
 */

/** Default icons (Foundry core SVGs) per condition id; a note's "Icon:" line wins. */
export const DEFAULT_ICONS = {
  prone: "icons/svg/falling.svg",
  grappled: "icons/svg/net.svg",
  immobilized: "icons/svg/net.svg",
  hidden: "icons/svg/invisible.svg",
  hindered: "icons/svg/downgrade.svg",
  intimidated: "icons/svg/terror.svg",
  taunted: "icons/svg/target.svg",
  asleep: "icons/svg/sleep.svg",
  mounted: "icons/svg/pawprint.svg",
  burn: "icons/svg/fire.svg",
  poisoned: "icons/svg/poison.svg",
  bleed: "icons/svg/blood.svg",
  regenerating: "icons/svg/regen.svg"
};

export const conditionId = name => String(name).trim().toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

/**
 * @param {string} markdown  A condition note.
 * @param {string} fallbackName  File name without extension.
 * @returns {{condition: {id: string, name: string, img: string, description: string, tokens: boolean}|null, warnings: string[]}}
 */
export function parseConditionNote(markdown, fallbackName) {
  const lines = String(markdown ?? "").replace(/\r/g, "").split("\n").map(line => line.trim()).filter(Boolean);
  const icon = lines.find(line => /^Icon:/i.test(line))?.replace(/^Icon:\s*/i, "").trim() ?? "";
  const main = lines.find(line => !/^Icon:/i.test(line) && !/^<%/.test(line)) ?? "";
  const colon = main.indexOf(":");
  if (colon < 0) return { condition: null, warnings: [`${fallbackName}: no "Name: effect" line`] };
  const name = main.slice(0, colon).replace(/\s*\(.*\)\s*$/, "").trim() || fallbackName;
  const description = main.slice(colon + 1).trim();
  const id = conditionId(name);
  const img = icon || DEFAULT_ICONS[id] || "icons/svg/aura.svg";
  const warnings = icon || DEFAULT_ICONS[id] ? [] : [`${name}: no icon (add a line "Icon: icons/svg/…" to the note)`];
  // A header can declare optional turns even when the description doesn't mention tokens.
  return { condition: { id, name, img, description, tokens: /\btokens?\b/i.test(description) || /\([^)]*\bturns?\b/i.test(main.slice(0, colon)) }, warnings };
}

/** Source of module/data/conditions.mjs. */
export function conditionsModule(conditions) {
  return "// Generated by tools/import-conditions.mjs from the vault (System Files/Listen/Conditions). Do not edit by hand.\n"
    + `export const CONDITIONS = ${JSON.stringify(conditions, null, 2)};\n`;
}
