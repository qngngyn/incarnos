/**
 * Update every vault-sourced compendium from the Obsidian vault in one go (the Obsidian "Update Foundry" button runs this).
 *
 *   node tools/sync-vault.mjs [vaultPath]
 *
 * vaultPath defaults to $INCARNOS_VAULT or C:/Users/mfgan/IncarnosPnp. For each pack: re-import the source JSON
 * from the vault notes, then rebuild the pack if its content changed since the last build (packs/.built.json).
 * Afterwards (even if a pack was locked or failed) it makes a backup with tools/backup.mjs in $INCARNOS_BACKUP_DIR
 * (default C:/Users/mfgan/IncarnosBackups) and deletes backups that are no longer needed.
 * Exit code 0 = done (open packs sync on the GM's next reload), 1 = error.
 */
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildPack, PackLockedError, readPackSource } from "./pack.mjs";
import { createBackup, DEFAULT_BACKUP_DIR } from "./backup.mjs";
import { missingKeyFiles } from "./key-files.mjs";

/** Packs whose truth is the vault. Add new vault importers here. */
const PACKS = [
  { name: "weapons", label: "Weapons", importer: "tools/import-weapons.mjs", lists: true },
  { name: "talents", label: "Talents", importer: "tools/import-talents.mjs", lists: true },
  { name: "races", label: "Races", importer: "tools/import-races.mjs", lists: true },
  { name: "spells", label: "Spells", importer: "tools/import-spells.mjs", lists: true },
  { name: "monsters", label: "Monsters", importer: "tools/import-monsters.mjs", lists: true },
  { name: "critical-failures", label: "Critical Failures", importer: "tools/import-critical-failures.mjs", lists: true },
  { name: "macros", label: "Macros" }, // Generated by import-critical-failures alongside the tables.
  { name: "handbook", label: "Handbook", importer: "tools/import-handbook.mjs", lists: true }
];

const root = fileURLToPath(new URL("..", import.meta.url));
const vault = process.argv[2] ?? process.env.INCARNOS_VAULT ?? "C:/Users/mfgan/IncarnosPnp";
const builtFile = join(root, "packs", ".built.json");
const built = existsSync(builtFile) ? JSON.parse(readFileSync(builtFile, "utf8")) : {};
const hash = docs => createHash("sha1").update(JSON.stringify(docs)).digest("hex");
const byId = docs => new Map(docs.filter(doc => doc._id).map(doc => [doc._id, JSON.stringify(doc)]));

if (!existsSync(vault)) { console.error(`Vault not found: ${vault}`); process.exit(1); }

let locked = false, failed = false, rebuilt = false;
for (const pack of PACKS) {
  try {
    const before = byId(existsSync(join(root, "packs", "_source", pack.name)) ? readPackSource(pack.name) : []);
    const args = pack.importer ? [join(root, pack.importer)] : [];
    if (pack.lists) args.push(join(vault, "System Files", "Listen"));
    const log = pack.importer ? execFileSync(process.execPath, args, { cwd: root, encoding: "utf8" }) : "";
    const warnings = log.split("\n").filter(line => line.startsWith("- ")).map(line => line.slice(2));
    // "~ " lines are information (e.g. unfinished monster notes), shown without counting as warnings.
    const notes = log.split("\n").filter(line => line.startsWith("~ ")).map(line => line.slice(2));
    const handbookSummary = log.split(/\r?\n/).find(line => line.startsWith("Handbook:"));
    if (handbookSummary) console.log(handbookSummary);

    const docs = readPackSource(pack.name);
    const after = byId(docs);
    const changed = [...after].filter(([id, json]) => before.get(id) !== json).length
      + [...before.keys()].filter(id => !after.has(id)).length;
    // Folders and embedded documents (an actor's items) are not counted.
    const count = docs.filter(doc => !doc._key?.startsWith("!folders!") && !doc._key?.includes(".")).length;
    const hasPack = existsSync(join(root, "packs", pack.name));

    if (hasPack && built[pack.name] === hash(docs)) {
      console.log(`${pack.label}: up to date (${count})`);
    } else {
      await buildPack(pack.name);
      built[pack.name] = hash(docs);
      writeFileSync(builtFile, JSON.stringify(built, null, 2) + "\n");
      rebuilt = true;
      console.log(`${pack.label}: updated (${count}${changed ? `, ${changed} changed` : ""})`);
    }
    for (const note of notes) console.log(`  · ${note}`);
    for (const warning of warnings) console.log(`  ! ${warning}`);
  } catch (error) {
    if (error instanceof PackLockedError) { locked = true; console.log(`${pack.label}: source updated; pack is open in Foundry, the world will pick up the changes on the GM's next reload (F5)`); }
    else { failed = true; console.log(`${pack.label}: failed: ${(error.stderr || error.message).toString().trim()}`); }
  }
}

// Conditions are not a compendium: they become Foundry's status effect list (module/data/conditions.mjs),
// which clients load at startup, so a change needs a reload (F5) instead of a world relaunch.
let reloadClients = false;
try {
  const log = execFileSync(process.execPath, [join(root, "tools", "import-conditions.mjs"), join(vault, "System Files", "Listen")], { cwd: root, encoding: "utf8" });
  const count = log.match(/^(\d+) conditions/m)?.[1] ?? "?";
  reloadClients = log.includes("(changed)");
  console.log(`Conditions: ${reloadClients ? "updated" : "up to date"} (${count})`);
  for (const warning of log.split("\n").filter(line => line.startsWith("- "))) console.log(`  ! ${warning.slice(2)}`);
} catch (error) {
  failed = true;
  console.log(`Conditions: failed: ${(error.stderr || error.message).toString().trim()}`);
}

// The vault's CLAUDE.md points Claude at key notes by full-path links ([[Welten/…/Monster Balancing]]).
// Obsidian rewrites them on a move; warn when one no longer resolves (moved outside Obsidian, renamed, deleted).
const missing = missingKeyFiles(vault);
if (missing.length) {
  console.log("Key files: links in CLAUDE.md that no longer resolve");
  for (const link of missing) console.log(`  ! CLAUDE.md links to "${link}", which does not exist (moved or renamed? fix the link)`);
}

try {
  const backup = createBackup({ vault, backupDir: process.env.INCARNOS_BACKUP_DIR || DEFAULT_BACKUP_DIR });
  console.log(`Backup: saved ${backup.name} (${backup.kept.length} backups kept${backup.deleted.length ? `, ${backup.deleted.length} old deleted` : ""})`);
} catch (error) {
  console.log(`Backup: failed\n  ! Backup failed: ${error.message}`);
}

if (locked) console.log("\nReload Foundry (F5) as the GM to sync compendiums from the vault and refresh owned spells. The world can stay open.");
else if (rebuilt) console.log("\nLaunch the world, or reload Foundry (F5) as the GM, to see the changes.");
else if (reloadClients) console.log("\nReload Foundry (F5) to see the new conditions.");
console.log("New system packs (Critical Failures, Macros and Incarnos Handbook) require a world relaunch, not just F5, the first time they are installed.");
process.exit(failed ? 1 : 0);
